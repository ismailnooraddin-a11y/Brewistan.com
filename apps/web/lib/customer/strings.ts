const DICTS: Record<Lang, Record<Key, string>> = { en, ar, ckb };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text = DICTS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
export type StringKey = Key;

export function pickLabel(label: Record<string, string> | null | undefined, lang: Lang): string {
  return label?.[lang] || label?.en || 'Free Coffee';
}
